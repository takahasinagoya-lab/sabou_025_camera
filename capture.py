import json
import logging
import time
import urllib.error
import urllib.request
from datetime import datetime, timedelta, timezone
from pathlib import Path

JST = timezone(timedelta(hours=9))

IMAGE_URL = "https://www.cbr.mlit.go.jp/tajimi/sabou/camera/images/S025N1L.jpg"
BASE_DIR = Path(__file__).resolve().parent
IMAGES_DIR = BASE_DIR / "images"
DATA_JS_PATH = BASE_DIR / "data.js"
LOG_PATH = BASE_DIR / "capture.log"

logging.basicConfig(
    filename=LOG_PATH,
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    encoding="utf-8",
)


def fetch_image(url: str, retries: int = 3, delay_sec: int = 5) -> bytes:
    """Download the live camera JPEG image with simple retries."""
    cache_buster = int(time.time())
    req = urllib.request.Request(
        f"{url}?t={cache_buster}",
        headers={
            "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64)",
            "Cache-Control": "no-cache",
            "Pragma": "no-cache",
        },
    )
    last_err: Exception | None = None
    for attempt in range(1, retries + 1):
        try:
            with urllib.request.urlopen(req, timeout=20) as resp:
                if resp.status != 200:
                    raise RuntimeError(f"HTTP {resp.status}")
                data = resp.read()
                if len(data) < 1024:
                    raise RuntimeError(f"Image too small ({len(data)} bytes)")
                return data
        except (urllib.error.URLError, TimeoutError, RuntimeError) as exc:
            last_err = exc
            logging.warning("Attempt %d/%d failed: %s", attempt, retries, exc)
            if attempt < retries:
                time.sleep(delay_sec)
    raise RuntimeError(f"Failed to download image after {retries} attempts: {last_err}")


def rebuild_data_js() -> dict[str, dict[str, str]]:
    """Scan the images directory and regenerate data.js for file:// viewing."""
    dates_map: dict[str, dict[str, str]] = {}
    if IMAGES_DIR.exists():
        for date_dir in sorted(IMAGES_DIR.iterdir(), reverse=True):
            if not date_dir.is_dir():
                continue
            hours_map: dict[str, str] = {}
            for img_file in sorted(date_dir.glob("*.jpg")):
                hour_key = img_file.stem
                if len(hour_key) == 2 and hour_key.isdigit():
                    hours_map[hour_key] = f"images/{date_dir.name}/{img_file.name}"
            if hours_map:
                dates_map[date_dir.name] = hours_map

    payload = {
        "updatedAt": datetime.now(JST).strftime("%Y-%m-%d %H:%M:%S"),
        "dates": dates_map,
    }
    js_content = (
        "// Auto-generated by capture.py\n"
        f"window.CAMERA_DATA = {json.dumps(payload, ensure_ascii=False, indent=2)};\n"
    )
    DATA_JS_PATH.write_text(js_content, encoding="utf-8")
    return dates_map


def main() -> None:
    now = datetime.now(JST)
    date_str = now.strftime("%Y-%m-%d")
    hour_str = now.strftime("%H")

    target_dir = IMAGES_DIR / date_str
    target_dir.mkdir(parents=True, exist_ok=True)
    target_path = target_dir / f"{hour_str}.jpg"

    try:
        image_bytes = fetch_image(IMAGE_URL)
        target_path.write_bytes(image_bytes)
        rebuild_data_js()
        logging.info("Saved %s (%d bytes)", target_path.relative_to(BASE_DIR), len(image_bytes))
    except Exception as exc:
        logging.error("Capture failed: %s", exc)
        # Still rebuild data.js in case directories exist
        rebuild_data_js()
        raise


if __name__ == "__main__":
    main()
